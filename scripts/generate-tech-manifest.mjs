import { readdirSync, readFileSync, writeFileSync } from "fs";
import { join, basename, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const TECH_BASE = join(ROOT, "public", "icons", "Tech-Icons");

const CATEGORY_ORDER = [
  { dir: "Brands", id: "Tech_Brands", label: "Marcas & SaaS" },
  { dir: "Cloud", id: "Tech_Cloud", label: "Cloud" },
  { dir: "Network", id: "Tech_Network", label: "Redes" },
  { dir: "Shapes", id: "Tech_Shapes", label: "Formas" },
];

// nomes de arquivo ficam em ASCII (evita problemas de encoding no Windows);
// a exibição ganha os acentos aqui
const NAME_FIXES = {
  "Conexao LAN": "Conexão LAN",
  Conexoes: "Conexões",
  "Camera CCTV": "Câmera CCTV",
  Seguranca: "Segurança",
  "Estacao de Trabalho": "Estação de Trabalho",
  "Memoria RAM": "Memória RAM",
  "Disco Rigido": "Disco Rígido",
  Usuario: "Usuário",
  Usuarios: "Usuários",
  "Antena Satelite": "Antena Satélite",
  Hexagono: "Hexágono",
  Pentagono: "Pentágono",
  Octogono: "Octógono",
  Triangulo: "Triângulo",
  Coracao: "Coração",
  "Balao de Fala": "Balão de Fala",
  Relogio: "Relógio",
};

function svgToDataUri(filePath) {
  const svg = readFileSync(filePath, "utf8").trim();
  const encoded = svg
    .replace(/\n/g, " ")
    .replace(/\s{2,}/g, " ")
    .replace(/#/g, "%23")
    .replace(/"/g, "'");
  return `data:image/svg+xml,${encoded}`;
}

const categories = [];
for (const { dir, id, label } of CATEGORY_ORDER) {
  const path = join(TECH_BASE, dir);
  let files = [];
  try {
    files = readdirSync(path).filter((f) => f.endsWith(".svg"));
  } catch {
    continue;
  }
  const icons = files.sort().map((filename) => {
    const raw = basename(filename, ".svg");
    const name = NAME_FIXES[raw] ?? raw;
    const iconId = `${id}_${raw.replace(/[^a-zA-Z0-9]/g, "_")}`;
    return { id: iconId, name, dataUri: svgToDataUri(join(path, filename)) };
  });
  if (icons.length > 0) {
    categories.push({ id, label, icons });
  }
}

const total = categories.reduce((a, c) => a + c.icons.length, 0);

const manifest = [
  `// AUTO-GENERATED by scripts/generate-tech-manifest.mjs — DO NOT EDIT`,
  `// Loaded on demand (dynamic import) — must stay out of the initial bundle.`,
  ``,
  `import type { AwsCategory, AwsIcon } from "./awsIcons";`,
  ``,
  `export const TECH_CATEGORIES: AwsCategory[] = ${JSON.stringify(
    categories,
  )};`,
  ``,
  `export const ALL_TECH_ICONS: AwsIcon[] = TECH_CATEGORIES.flatMap(`,
  `  (c) => c.icons,`,
  `);`,
  ``,
].join("\n");

writeFileSync(
  join(ROOT, "excalidraw-app", "data", "techIcons.ts"),
  manifest,
  "utf8",
);

const meta = [
  `// AUTO-GENERATED by scripts/generate-tech-manifest.mjs — DO NOT EDIT`,
  `export const TOTAL_TECH_ICON_COUNT = ${total};`,
  ``,
].join("\n");

writeFileSync(
  join(ROOT, "excalidraw-app", "data", "techIconsMeta.ts"),
  meta,
  "utf8",
);

for (const c of categories) {
  console.log(`   ${c.label}: ${c.icons.length} icons`);
}
console.log(`✅ techIcons.ts gerado — TOTAL: ${total}`);
